use std::{fs, path::Path};

fn main() {
  let root = Path::new(env!("CARGO_MANIFEST_DIR"))
    .parent()
    .unwrap()
    .parent()
    .unwrap();
  let output = root.join("src/windows/audio_bindings.rs");
  windows_bindgen::builder()
    .output(&output)
    .flat()
    .rustfmt("tab_spaces=2")
    .filters([
      "IMMDeviceEnumerator::{EnumAudioEndpoints,GetDefaultAudioEndpoint}",
      "IMMDeviceCollection::{GetCount,Item}",
      "IMMDevice::{GetId,Activate}",
      "IAudioSessionManager2::{GetSessionEnumerator,RegisterSessionNotification}",
      "IAudioSessionEnumerator::{GetCount,GetSession}",
      "IAudioSessionControl::{GetDisplayName,GetState,RegisterAudioSessionNotification,UnregisterAudioSessionNotification}",
      "IAudioSessionControl2::GetProcessId",
      "IAudioSessionEvents",
      "IAudioSessionNotification",
      "AudioSessionStateActive",
      "E_NOTIMPL",
      "MMDeviceEnumerator",
      "DEVICE_STATE_ACTIVE",
      "eCapture",
      "eCommunications",
      "eConsole",
      "CoCreateInstance",
      "CLSCTX_ALL",
      "CoInitializeEx",
      "COINIT_MULTITHREADED",
    ])
    .implements([
      "Windows.Win32.IAudioSessionEvents",
      "Windows.Win32.IAudioSessionNotification",
    ])
    .write();

  let bindings = fs::read_to_string(&output).unwrap();
  fs::write(
    output,
    format!(
      "// Generated by windows-bindgen 0.100.0. Do not edit directly.\n\
       // Regenerate: cargo run --locked --manifest-path tools/windows-audio-bindings/Cargo.toml\n\n{bindings}"
    ),
  )
  .unwrap();
}
